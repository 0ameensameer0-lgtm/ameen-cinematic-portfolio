let currentLanguage = localStorage.getItem('language') || 'ar';
let currentTheme = localStorage.getItem('theme') || 'dark';
let portfolioProjects = [];
let portfolioCategories = [];
let pageData = {
  skills: [],
  services: [],
  certificates: []
};

async function initializePage() {
  applyTheme();
  applyLanguage();
  setupEventListeners();
  await loadData();
  updateActiveNav();
  if (typeof initAnimations === 'function') {
    initAnimations();
  }
}

function setupEventListeners() {
  const langToggle = document.getElementById('langToggle');
  const themeToggle = document.getElementById('themeToggle');
  const menuToggle = document.getElementById('menuToggle');
  const navMenu = document.getElementById('navMenu');

  if (langToggle) {
    langToggle.addEventListener('click', toggleLanguage);
  }

  if (themeToggle) {
    themeToggle.addEventListener('click', toggleTheme);
  }

  if (menuToggle && navMenu) {
    menuToggle.addEventListener('click', () => {
      navMenu.classList.toggle('active');
    });
  }

  document.querySelectorAll('.nav-link').forEach((link) => {
    link.addEventListener('click', () => {
      navMenu.classList.remove('active');
    });
  });

  const contactForm = document.getElementById('contactForm');
  if (contactForm) {
    contactForm.addEventListener('submit', handleContactForm);
  }

  window.addEventListener('scroll', updateActiveNav, { passive: true });
}

function toggleTheme() {
  currentTheme = currentTheme === 'dark' ? 'light' : 'dark';
  localStorage.setItem('theme', currentTheme);
  applyTheme();
}

function applyTheme() {
  const body = document.body;
  const themeToggle = document.getElementById('themeToggle');

  body.classList.toggle('light-mode', currentTheme === 'light');

  if (themeToggle) {
    themeToggle.innerHTML = currentTheme === 'light'
      ? '<i class="fa-regular fa-sun"></i>'
      : '<i class="fa-regular fa-moon"></i>';
  }
}

function toggleLanguage() {
  currentLanguage = currentLanguage === 'ar' ? 'en' : 'ar';
  localStorage.setItem('language', currentLanguage);
  applyLanguage();
  rerenderDynamicContent();
}

function applyLanguage() {
  const html = document.documentElement;
  const langToggle = document.getElementById('langToggle');
  const t = translations[currentLanguage];

  html.lang = currentLanguage;
  html.dir = currentLanguage === 'ar' ? 'rtl' : 'ltr';

  if (langToggle) {
    langToggle.textContent = currentLanguage === 'ar' ? 'EN' : 'AR';
  }

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    if (t[key]) {
      node.textContent = t[key];
    }
  });

  const nameField = document.getElementById('name');
  const emailField = document.getElementById('email');
  const messageField = document.getElementById('message');

  if (nameField) nameField.placeholder = currentLanguage === 'ar' ? 'اكتب اسمك' : 'Write your name';
  if (emailField) emailField.placeholder = currentLanguage === 'ar' ? 'name@example.com' : 'name@example.com';
  if (messageField) {
    messageField.placeholder = currentLanguage === 'ar'
      ? 'اكتب نبذة سريعة عن مشروعك أو فكرتك'
      : 'Tell me a bit about your project or idea';
  }
}

async function loadData() {
  try {
    const [portfolioRes, skillsRes, servicesRes, certificatesRes] = await Promise.all([
      fetch('/api/portfolio'),
      fetch('/api/skills'),
      fetch('/api/services'),
      fetch('/api/certificates')
    ]);

    const portfolioData = await portfolioRes.json();
    const skillsData = await skillsRes.json();
    const servicesData = await servicesRes.json();
    const certificatesData = await certificatesRes.json();

    portfolioProjects = Array.isArray(portfolioData.projects) ? portfolioData.projects : [];
    pageData.skills = Array.isArray(skillsData.skills) ? skillsData.skills : [];
    pageData.services = Array.isArray(servicesData.services) ? servicesData.services : [];
    pageData.certificates = Array.isArray(certificatesData.certificates) ? certificatesData.certificates : [];

    portfolioCategories = [...new Set(portfolioProjects.map((project) => project.category).filter(Boolean))];

    renderSkills(pageData.skills);
    renderServices(pageData.services);
    renderPortfolio(portfolioProjects);
    renderCertificates(pageData.certificates);
    updateMetrics();
  } catch (error) {
    console.error('Error loading data:', error);
  }
}

function rerenderDynamicContent() {
  renderSkills(pageData.skills);
  renderServices(pageData.services);
  renderPortfolio(portfolioProjects);
  renderCertificates(pageData.certificates);
  updateMetrics();
}

function updateMetrics() {
  const projectsCount = document.getElementById('projectsCount');
  const skillsCount = document.getElementById('skillsCount');
  const servicesCount = document.getElementById('servicesCount');

  const skillItemsCount = pageData.skills.reduce((sum, group) => sum + (group.items ? group.items.length : 0), 0);

  if (projectsCount) projectsCount.textContent = String(portfolioProjects.length).padStart(2, '0');
  if (skillsCount) skillsCount.textContent = String(skillItemsCount).padStart(2, '0');
  if (servicesCount) servicesCount.textContent = String(pageData.services.length).padStart(2, '0');
}

function renderSkills(skillsData) {
  const skillsList = document.getElementById('skillsList');
  if (!skillsList) return;

  skillsList.innerHTML = skillsData.map((group) => `
    <article class="skill-group">
      <h3>${group.category}</h3>
      <div class="skill-tags">
        ${(group.items || []).map((item) => `<span class="skill-tag">${item}</span>`).join('')}
      </div>
    </article>
  `).join('');
}

function renderServices(servicesData) {
  const servicesList = document.getElementById('servicesList');
  const t = translations[currentLanguage];
  if (!servicesList) return;

  servicesList.innerHTML = servicesData.map((service, index) => `
    <article class="service-card">
      <div class="service-index">
        <span>${String(index + 1).padStart(2, '0')} / ${t.serviceLabel}</span>
        <div class="service-icon"><i class="${service.icon}"></i></div>
      </div>
      <h3>${service.title}</h3>
      <p>${service.description}</p>
    </article>
  `).join('');
}

function renderPortfolio(projects) {
  const portfolioList = document.getElementById('portfolioList');
  const filterButtons = document.getElementById('filterButtons');
  const t = translations[currentLanguage];
  if (!portfolioList || !filterButtons) return;

  filterButtons.innerHTML = [
    `<button class="filter-btn active" data-filter="all">${t.all}</button>`,
    ...portfolioCategories.map((category) => `
      <button class="filter-btn" data-filter="${escapeAttribute(category)}">${category}</button>
    `)
  ].join('');

  portfolioList.innerHTML = projects.map((project) => `
    <article class="portfolio-item" data-category="${escapeAttribute(project.category)}">
      <div class="portfolio-media">
        <img src="${project.image}" alt="${project.title}">
      </div>
      <div class="portfolio-body">
        <div class="portfolio-meta">
          <span>${t.categoryLabel}: ${project.category}</span>
          <span>${t.yearLabel}: ${project.date || '-'}</span>
        </div>
        <h3>${project.title}</h3>
        <p>${project.description}</p>
        <div class="portfolio-tags">
          ${(project.tags || []).map((tag) => `<span>${tag}</span>`).join('')}
        </div>
      </div>
    </article>
  `).join('');

  document.querySelectorAll('[data-filter]').forEach((button) => {
    button.addEventListener('click', () => {
      document.querySelectorAll('[data-filter]').forEach((btn) => btn.classList.remove('active'));
      button.classList.add('active');
      filterPortfolio(button.getAttribute('data-filter'));
    });
  });
}

function filterPortfolio(filter) {
  document.querySelectorAll('.portfolio-item').forEach((item) => {
    const shouldShow = filter === 'all' || item.getAttribute('data-category') === filter;
    item.style.display = shouldShow ? 'block' : 'none';
    item.style.opacity = shouldShow ? '1' : '0';
  });
}

function renderCertificates(certificatesData) {
  const certificatesList = document.getElementById('certificatesList');
  const t = translations[currentLanguage];
  if (!certificatesList) return;

  certificatesList.innerHTML = certificatesData.map((cert) => `
    <article class="certificate-card">
      <img src="${cert.image}" alt="${cert.title}">
      <h3>${cert.title}</h3>
      <p>${cert.issuer}</p>
      <p style="margin-top: 8px;">${t.yearLabel}: ${cert.date}</p>
      <a class="cert-link" href="${cert.credential}" target="_blank" rel="noreferrer">
        <i class="fa-solid fa-arrow-up-right-from-square"></i>
        <span>${t.certLink}</span>
      </a>
    </article>
  `).join('');
}

async function handleContactForm(event) {
  event.preventDefault();

  const form = event.currentTarget;
  const status = document.getElementById('formStatus');
  const t = translations[currentLanguage];

  const payload = {
    name: document.getElementById('name').value.trim(),
    email: document.getElementById('email').value.trim(),
    message: document.getElementById('message').value.trim()
  };

  try {
    if (status) status.textContent = currentLanguage === 'ar' ? 'جاري الإرسال...' : 'Sending...';

    const response = await fetch('/api/contact', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify(payload)
    });

    const data = await response.json();

    if (!response.ok || !data.success) {
      throw new Error('Request failed');
    }

    form.reset();
    if (status) status.textContent = t.sentSuccess;
  } catch (error) {
    console.error(error);
    if (status) status.textContent = t.sentError;
  }
}

function updateActiveNav() {
  const sections = document.querySelectorAll('main section[id]');
  const scrollPoint = window.scrollY + 140;

  sections.forEach((section) => {
    const link = document.querySelector(`.nav-link[href="#${section.id}"]`);
    if (!link) return;

    const top = section.offsetTop;
    const bottom = top + section.offsetHeight;
    const active = scrollPoint >= top && scrollPoint < bottom;

    link.classList.toggle('active', active);
  });
}

function escapeAttribute(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initializePage);
} else {
  initializePage();
}
